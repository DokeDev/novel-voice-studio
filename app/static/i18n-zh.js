    function translateString(value) {
        if (!value || !/[A-Za-z]/.test(value)) return value;
        const leading = value.match(/^\s*/)[0];
        const trailing = value.match(/\s*$/)[0];
        const core = value.trim();
        if (!core) return value;
        if (exact.has(core)) return leading + exact.get(core) + trailing;

        let translated = core;
        for (const [source, target] of phrases) {
            if (translated.includes(source)) translated = translated.split(source).join(target);
        }
        for (const [pattern, replacement] of replacements) {
            translated = translated.replace(pattern, replacement);
        }
        return translated === core ? value : leading + translated + trailing;
    }

    function translateNode(root) {
        if (!root) return;
        if (root.nodeType === Node.TEXT_NODE) {
            const parent = root.parentElement;
            if (parent && !parent.closest('script, style, textarea, [data-no-translate]')) {
                const translated = translateString(root.nodeValue);
                if (translated !== root.nodeValue) root.nodeValue = translated;
            }
            return;
        }
        if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;

        if (root.nodeType === Node.ELEMENT_NODE) {
            for (const attr of ['placeholder', 'title', 'aria-label']) {
                if (root.hasAttribute(attr)) {
                    const value = root.getAttribute(attr);
                    const translated = translateString(value);
                    if (translated !== value) root.setAttribute(attr, translated);
                }
            }
        }

        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        const nodes = [];
        while (walker.nextNode()) nodes.push(walker.currentNode);
        nodes.forEach(node => translateNode(node));

        if (root.querySelectorAll) {
            root.querySelectorAll('[placeholder], [title], [aria-label]').forEach(element => {
                for (const attr of ['placeholder', 'title', 'aria-label']) {
                    if (!element.hasAttribute(attr)) continue;
                    const value = element.getAttribute(attr);
                    const translated = translateString(value);
                    if (translated !== value) element.setAttribute(attr, translated);
                }
            });
        }
    }

    translateNode(document.body);

    const observer = new MutationObserver(mutations => {
        for (const mutation of mutations) {
            if (mutation.type === 'characterData') {
                translateNode(mutation.target);
            }
            mutation.addedNodes.forEach(translateNode);
        }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });

